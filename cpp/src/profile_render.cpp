std::string shell_quote(const std::string& value) {
    if (value.empty()) {
        return "''";
    }
    if (value.find_first_not_of("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_@%+=:,./-") == std::string::npos) {
        return value;
    }
    std::string result = "'";
    for (char ch : value) {
        if (ch == '\'') {
            result += "'\"'\"'";
        } else {
            result += ch;
        }
    }
    result += "'";
    return result;
}

std::string assignment(const std::string& name, const std::string& value) {
    return name + "=" + shell_quote(value) + "\n";
}

std::string assignment(const std::string& name, const char* value) {
    return assignment(name, std::string(value));
}

std::string assignment(const std::string& name, bool value) {
    return name + "=" + std::string(value ? "true" : "false") + "\n";
}

std::string assignment(const std::string& name, long long value) {
    return name + "=" + std::to_string(value) + "\n";
}

